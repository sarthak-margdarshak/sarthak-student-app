import { useContext } from "react";
import { ThemeContext } from "./ThemeContext";

export const useThemeContext = () => {
  const themeContext = useContext(ThemeContext);
  if (!themeContext)
    throw new Error(
      "useThemeContext context must be used inside ThemeProvider"
    );
  return themeContext;
};
